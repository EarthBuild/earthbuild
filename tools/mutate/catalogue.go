package main

// Mutant is one deliberate defect and the package that should notice it.
//
// The anchor is a literal snippet of the source. That is brittle on purpose:
// when the code moves, the anchor stops matching and the sweep says `ANCHOR`
// rather than quietly testing nothing. A catalogue that silently stopped
// applying would be worse than none, because it would keep reporting success.
type Mutant struct {
	// Name says which mechanism is being deleted, and which invariant it holds.
	Name string
	// File is repo-relative.
	File string
	// Anchor must appear exactly once in File.
	Anchor string
	// Replacement is what it becomes. Two requirements, and the second cost a
	// false survivor before it was written down (E253):
	//
	//   - it has to compile, or the mutant tests the compiler rather than the
	//     suite;
	//   - it has to **remove the mechanism** rather than stand next to it. A
	//     replacement that leaves the refusal it was meant to delete still
	//     refuses, and the tool then reports a guarded mechanism as unguarded -
	//     indistinguishable, in the report, from the real thing.
	//
	// A mutant that no test can kill is more likely to be wrong than the suite
	// is. That is the first thing to check when one survives.
	Replacement string
	// Package is what to run. Narrow, because the sweep runs it once per mutant.
	Package string
	// OS names the only platform this mechanism exists on, or is empty for one
	// that exists everywhere. A sweep on another platform reports it as unrun
	// rather than as unguarded - a mutation the platform compiled away looks
	// exactly like one nothing tested (E241).
	//
	// One field rather than a flag per platform, because the two-flag version
	// has a meaningless state - both set - and the field is read in a place that
	// would have to decide what that meant. It was `Linux bool` until a sweep on
	// Linux reported three darwin-only mechanisms as unguarded, which is the
	// same fault E241 records, arriving from the other direction: the entries
	// had no way to say which platform they belonged to.
	OS string
}

